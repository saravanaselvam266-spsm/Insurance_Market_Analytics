SELECT
    NULLIF(TRIM(POLICYID), '') AS POLICY_ID,
    NULLIF(TRIM(CUSTOMERID), '') AS CUSTOMER_ID,
    INITCAP(TRIM(PRODUCTTYPE)) AS PRODUCT_TYPE,
    NULLIF(TRIM(INSURANCEPARTNER), '') AS INSURANCE_PARTNER,
    TRY_TO_DECIMAL(NULLIF(TRIM(PREMIUMAMOUNT), ''), 18, 2) AS PREMIUM_AMOUNT,
    INITCAP(TRIM(POLICYSTATUS)) AS POLICY_STATUS,
    TRY_TO_DATE(NULLIF(TRIM(ISSUEDATE), '')) AS ISSUE_DATE,
    TRY_TO_DATE(NULLIF(TRIM(EXPIRYDATE), '')) AS EXPIRY_DATE,
    INITCAP(TRIM(SALESCHANNEL)) AS SALES_CHANNEL,
    INITCAP(TRIM(EMIRATES)) AS EMIRATE,
    NULLIF(TRIM(ADVISORID), '') AS ADVISOR_ID,
    _SOURCE_FILE_NAME,
    _INGESTED_TS
FROM {{ source('insurancemarket', 'POLICIES') }}