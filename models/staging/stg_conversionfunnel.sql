SELECT
    NULLIF(TRIM(LEADID), '') AS LEAD_ID,
    TRY_TO_DATE(NULLIF(TRIM(QUOTEDATE), '')) AS QUOTE_DATE,
    INITCAP(TRIM(PRODUCTTYPE)) AS PRODUCT_TYPE,
    INITCAP(TRIM(CHANNEL)) AS CHANNEL,
    INITCAP(TRIM(LEADSOURCE)) AS LEAD_SOURCE,

    TRY_TO_BOOLEAN(NULLIF(TRIM(STAGE1_FORMSUBMITTED), '')) AS STAGE1_FORM_SUBMITTED,
    TRY_TO_DATE(NULLIF(TRIM(STAGE1_DATE), '')) AS STAGE1_DATE,

    TRY_TO_BOOLEAN(NULLIF(TRIM(STAGE2_OPTIONSREVIEWED), '')) AS STAGE2_OPTIONS_REVIEWED,
    TRY_TO_DATE(NULLIF(TRIM(STAGE2_DATE), '')) AS STAGE2_DATE,

    TRY_TO_BOOLEAN(NULLIF(TRIM(ADVISORCONSULTED), '')) AS ADVISOR_CONSULTED,

    TRY_TO_BOOLEAN(NULLIF(TRIM(STAGE3_DOCUMENTSUPLOADED), '')) AS STAGE3_DOCUMENTS_UPLOADED,
    TRY_TO_DATE(NULLIF(TRIM(STAGE3_DATE), '')) AS STAGE3_DATE,

    TRY_TO_BOOLEAN(NULLIF(TRIM(POLICYPURCHASED), '')) AS POLICY_PURCHASED,
    TRY_TO_DATE(NULLIF(TRIM(PURCHASEDATE), '')) AS PURCHASE_DATE,

    NULLIF(TRIM(DROPOFFREASON), '') AS DROPOFF_REASON,

    _SOURCE_FILE_NAME,
    _INGESTED_TS

FROM {{ source('insurancemarket', 'CONVERSIONFUNNEL') }}
