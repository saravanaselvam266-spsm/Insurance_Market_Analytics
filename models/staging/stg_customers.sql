
SELECT
    NULLIF(TRIM(CUSTOMERID), '') AS CUSTOMER_ID,
    NULLIF(TRIM(CUSTOMERNAME), '') AS CUSTOMER_NAME,
    TRY_TO_NUMBER(NULLIF(TRIM(AGE), '')) AS AGE,
    UPPER(NULLIF(TRIM(GENDER), '')) AS GENDER,
    INITCAP(TRIM(EMIRATES)) AS EMIRATE,
    NULLIF(TRIM(CUSTOMERSEGMENT), '') AS CUSTOMER_SEGMENT,
    TRY_TO_DATE(NULLIF(TRIM(REGISTRATIONDATE), '')) AS REGISTRATION_DATE,
    TRY_TO_BOOLEAN(NULLIF(TRIM(MYALFREDMEMBER), '')) AS MYALFRED_MEMBER,
    TRY_TO_NUMBER(NULLIF(TRIM(CUSTOMERRATING), '')) AS CUSTOMER_RATING,
    _SOURCE_FILE_NAME,
    _INGESTED_TS
FROM {{ source('insurancemarket', 'CUSTOMERS') }}
