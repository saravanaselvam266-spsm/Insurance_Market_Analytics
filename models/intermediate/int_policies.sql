SELECT
    POLICY_ID,
    CUSTOMER_ID,
    PRODUCT_TYPE,
    INSURANCE_PARTNER,
    PREMIUM_AMOUNT,
    POLICY_STATUS,
    ISSUE_DATE,
    EXPIRY_DATE,
    SALES_CHANNEL,
    EMIRATE,
    ADVISOR_ID,

    CASE
        WHEN UPPER(TRIM(POLICY_STATUS)) = 'CANCELLED'
        THEN TRUE
        ELSE FALSE
    END AS IS_CANCELLED,

    PREMIUM_AMOUNT AS GROSS_WRITTEN_PREMIUM,

    CASE
        WHEN UPPER(TRIM(POLICY_STATUS)) = 'CANCELLED'
        THEN 0
        ELSE COALESCE(PREMIUM_AMOUNT, 0)
    END AS NET_WRITTEN_PREMIUM,

    _SOURCE_FILE_NAME,
    _INGESTED_TS

FROM {{ ref('stg_policies') }}
