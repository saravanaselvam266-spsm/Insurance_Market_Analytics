WITH funnel_metrics AS (
    SELECT
        COALESCE(
            L.MARKETING_CHANNEL_GROUP,
            'Unknown'
        ) AS MARKETING_CHANNEL_GROUP,
        COUNT(*) AS TOTAL_LEADS,
        COUNT_IF(F.POLICY_PURCHASED) AS TOTAL_PURCHASES
    FROM {{ ref('fact_lead_funnel') }} F
    LEFT JOIN {{ ref('dim_sales_channel') }} SC
        ON F.SALES_CHANNEL_SK = SC.SALES_CHANNEL_SK
    LEFT JOIN {{ ref('lkp_marketing_channel_group') }} L
        ON SC.SALES_CHANNEL = L.SALES_CHANNEL
    GROUP BY L.MARKETING_CHANNEL_GROUP
),

campaign_metrics AS (
    SELECT
        COALESCE(
            L.MARKETING_CHANNEL_GROUP,
            'Unknown'
        ) AS MARKETING_CHANNEL_GROUP,
        SUM(C.ACTUAL_SPEND) AS TOTAL_CAMPAIGN_SPEND,
        SUM(C.LEADS_GENERATED) AS CAMPAIGN_LEADS_GENERATED,
        SUM(C.CONVERSIONS) AS CAMPAIGN_CONVERSIONS
    FROM {{ ref('fact_campaign_performance') }} C
    LEFT JOIN {{ ref('dim_campaign') }} DC
        ON C.CAMPAIGN_SK = DC.CAMPAIGN_SK
    LEFT JOIN {{ ref('lkp_marketing_channel_group') }} L
        ON DC.CHANNEL = L.SALES_CHANNEL
    GROUP BY L.MARKETING_CHANNEL_GROUP
)

SELECT
    COALESCE(
        F.MARKETING_CHANNEL_GROUP,
        C.MARKETING_CHANNEL_GROUP
    ) AS MARKETING_CHANNEL_GROUP,
    COALESCE(F.TOTAL_LEADS, 0) AS TOTAL_LEADS,
    COALESCE(F.TOTAL_PURCHASES, 0) AS TOTAL_PURCHASES,
    COALESCE(C.TOTAL_CAMPAIGN_SPEND, 0) AS TOTAL_CAMPAIGN_SPEND,
    COALESCE(C.CAMPAIGN_LEADS_GENERATED, 0) AS CAMPAIGN_LEADS_GENERATED,
    COALESCE(C.CAMPAIGN_CONVERSIONS, 0) AS CAMPAIGN_CONVERSIONS
FROM funnel_metrics F
FULL OUTER JOIN campaign_metrics C
    ON F.MARKETING_CHANNEL_GROUP = C.MARKETING_CHANNEL_GROUP
