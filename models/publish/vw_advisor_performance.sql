SELECT
    a.ADVISOR_SK,
    a.ADVISOR_ID,
    a.ADVISOR_NAME,
    a.TEAM,
    a.TARGET_POLICIES,
    a.TARGET_REVENUE,

    COUNT(f.POLICY_ID) AS TOTAL_POLICIES,

    COALESCE(SUM(f.GROSS_WRITTEN_PREMIUM), 0)
        AS TOTAL_GROSS_WRITTEN_PREMIUM,

    COALESCE(SUM(f.NET_WRITTEN_PREMIUM), 0)
        AS TOTAL_NET_WRITTEN_PREMIUM,

    COUNT_IF(f.IS_CANCELLED = TRUE)
        AS CANCELLED_POLICIES,

    CASE
        WHEN a.TARGET_POLICIES > 0
        THEN COUNT(f.POLICY_ID) * 100.0 / a.TARGET_POLICIES
        ELSE NULL
    END AS POLICY_TARGET_ACHIEVEMENT_PERCENT,

    CASE
        WHEN a.TARGET_REVENUE > 0
        THEN COALESCE(SUM(f.GROSS_WRITTEN_PREMIUM), 0)
             * 100.0 / a.TARGET_REVENUE
        ELSE NULL
    END AS REVENUE_TARGET_ACHIEVEMENT_PERCENT

FROM {{ ref('dim_advisor') }} a

LEFT JOIN {{ ref('fact_policy') }} f
    ON a.ADVISOR_SK = f.ADVISOR_SK

GROUP BY
    a.ADVISOR_SK,
    a.ADVISOR_ID,
    a.ADVISOR_NAME,
    a.TEAM,
    a.TARGET_POLICIES,
    a.TARGET_REVENUE
